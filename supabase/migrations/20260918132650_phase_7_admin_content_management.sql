-- Phase 7: secure administrator content management for group trips,
-- resources, and blog posts.

-- Capability used by the browser admin portal. Administrator membership is
-- still anchored to auth.users through admin_users.id.
alter table public.admin_users
  add column if not exists can_edit_resources boolean not null default true;

-- Content fields needed by the public pages and editor.
alter table public.trips
  add column if not exists hero_kicker text,
  add column if not exists booking_deadline date,
  add column if not exists is_featured boolean not null default false,
  add column if not exists sort_order integer not null default 0;

update public.trips set status = 'completed'
where dates_end < current_date and status = 'active';

alter table public.trips alter column status set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'trips_status_check'
      and conrelid = 'public.trips'::regclass
  ) then
    alter table public.trips
      add constraint trips_status_check
      check (status in ('draft', 'active', 'completed', 'archived', 'cancelled'));
  end if;
end $$;

alter table public.resources
  add column if not exists updated_at timestamptz not null default now(),
  add column if not exists created_by uuid references auth.users(id) on delete set null,
  add column if not exists updated_by uuid references auth.users(id) on delete set null;

alter table public.blog_posts
  add column if not exists link_url text,
  add column if not exists published_at timestamptz,
  add column if not exists created_by uuid references auth.users(id) on delete set null,
  add column if not exists updated_by uuid references auth.users(id) on delete set null;

-- The existing empty blog table had a required bigint ID without a default.
-- Give it an identity so browser inserts remain safe under concurrent use.
do $$
begin
  if pg_get_serial_sequence('public.blog_posts', 'id') is null then
    alter table public.blog_posts
      alter column id add generated by default as identity;
  end if;
end $$;

-- Remove repeated seed rows while keeping the oldest canonical resource.
delete from public.resources
where resource_id in (
  select resource_id
  from (
    select resource_id,
           row_number() over (
             partition by lower(trim(title)), lower(trim(coalesce(category, '')))
             order by created_at nulls last, resource_id
           ) as duplicate_number
    from public.resources
  ) ranked
  where duplicate_number > 1
);

create unique index if not exists resources_title_category_unique
  on public.resources (lower(trim(title)), lower(trim(coalesce(category, ''))));

