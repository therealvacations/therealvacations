on storage.objects for update
to authenticated
using (
  bucket_id = 'content-media'
  and exists (
    select 1 from public.admin_users au where au.id = (select auth.uid())
  )
)
with check (
  bucket_id = 'content-media'
  and exists (
    select 1 from public.admin_users au where au.id = (select auth.uid())
  )
);
create policy "content_admins_delete_media"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'content-media'
  and exists (
    select 1 from public.admin_users au where au.id = (select auth.uid())
