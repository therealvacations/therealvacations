create policy "public_reads_active_trips"
on public.trips for select
to anon, authenticated
using (status = 'active');

create policy "trip_admins_read_all"
on public.trips for select
to authenticated
using (
  exists (
    select 1 from public.admin_users au
    where au.id = (select auth.uid()) and au.can_edit_trips
  )
);

create policy "travelers_read_booked_trips"
on public.trips for select
to authenticated
using (
  exists (
    select 1 from public.bookings b
    where b.trip_id = trips.trip_id
      and b.user_id = (select auth.uid())
  )
);

create policy "trip_admins_insert"
on public.trips for insert
to authenticated
with check (
  exists (
    select 1 from public.admin_users au
    where au.id = (select auth.uid()) and au.can_edit_trips
  )
);
create policy "trip_admins_update"
on public.trips for update
to authenticated
using (
  exists (
    select 1 from public.admin_users au
    where au.id = (select auth.uid()) and au.can_edit_trips
  )
)
with check (
  exists (
    select 1 from public.admin_users au
    where au.id = (select auth.uid()) and au.can_edit_trips
  )
);
create policy "trip_admins_delete_unbooked"
on public.trips for delete
to authenticated
using (
  exists (
    select 1 from public.admin_users au
    where au.id = (select auth.uid()) and au.can_edit_trips
  )
  and not exists (
    select 1 from public.bookings b where b.trip_id = trips.trip_id
  )
);

